"""Writes docs/reports/SPANISH_REVIEW.md: every Spanish verdict label, factor name, quiz question and option, side by side with the
English, so a native speaker can review them. Style: Mexican Spanish (rentar, auto, departamento, computadora; decimals with a
point: 2.5 horas). Run after changing data or code: python3 tests/spanish_review.py"""
import pathlib
from harness import sync_playwright, route, PAGE, CHROME
ROOT = pathlib.Path(__file__).resolve().parent.parent
with sync_playwright() as p:
    b = p.chromium.launch(executable_path=CHROME); pg = b.new_page(); pg.route('**/*', route)
    pg.goto('file://' + PAGE); pg.wait_for_timeout(700)
    S = pg.evaluate("()=>window.__atlas.strings()"); b.close()
STR, QSTR, FSTR = S['STR'], S['QSTR'], S['FSTR']
md = ["# Spanish review sheet", "", "Generated by `tests/spanish_review.py`. Style chosen: **Mexican Spanish** (the main audience is Mexican-American):",
      "*rentar / renta*, *auto*, *manejar*, *departamento*, *recámara*, *computadora*, *colonia*; decimals with a point (*2.5 horas*), thousands with a comma.",
      "Please mark anything that sounds unnatural, too formal, or Spain-specific, and suggest a replacement in the last column.", "",
      "## Verdict labels", "", "| English | Español | Suggestion |", "|---|---|---|"]
md += [f"| {STR['en']['tiers'][k]} | {STR['es']['tiers'][k]} | |" for k in STR['en']['tiers']]
md += ["", "## Factor names (strength / weakness)", "", "| English | Español | Suggestion |", "|---|---|---|"]
md += [f"| {FSTR['en'][k][0]} / {FSTR['en'][k][1]} | {FSTR['es'][k][0]} / {FSTR['es'][k][1]} | |" for k in FSTR['en']]
md += ["", "## Quiz", ""]
for k in QSTR['en']:
    md += [f"### {k}", "", f"**EN:** {QSTR['en'][k][0]}", "", f"**ES:** {QSTR['es'][k][0]}", "", "| English option | Opción en español | Suggestion |", "|---|---|---|"]
    md += [f"| {a} | {b_} | |" for a, b_ in zip(QSTR['en'][k][1], QSTR['es'][k][1])] + [""]
md += ["## Buttons and short labels", "", "| Key | English | Español | Suggestion |", "|---|---|---|---|"]
for k, v in STR['en'].items():
    e = STR['es'].get(k)
    if isinstance(v, str) and isinstance(e, str) and len(v) <= 60 and '<' not in v: md.append(f"| {k} | {v} | {e} | |")
(ROOT / 'docs' / 'reports' / 'SPANISH_REVIEW.md').write_text('\n'.join(md) + '\n', encoding='utf8')
print('wrote docs/reports/SPANISH_REVIEW.md:', len(md), 'lines')
