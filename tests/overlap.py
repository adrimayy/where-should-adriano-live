"""Do any two factors measure the same thing? (Saltelli & Saisana.) Correlations between every pair of factors, across cities and
across countries, using published values only (exact within-band values where available); a principal-components analysis; and
every pair above 0.7 flagged. Writes docs/OVERLAP.md. Run after build.py: python3 tests/overlap.py"""
import json, pathlib, numpy as np
ROOT = pathlib.Path(__file__).resolve().parent.parent
D = json.load(open(ROOT / 'build' / 'final.json', encoding='utf8'))
IDX = dict(clim=0, jobs=1, hlth=2, free=3, safe=4, move=5, cult=7, pay=8, open=9, happy=11, women=12, lgbt=13, cost=14, commute=15, home=16)
NAMES = dict(clim='Climate', jobs='Job market', hlth='Healthcare', free='Freedom', safe='Safety', move='Car dependence', cult='Things happening',
             pay='Money after rent', open='Welcoming', happy='Life satisfaction', women="Women's rights", lgbt='LGBTQ+', cost='Cost of living', commute='Commute', home='Housing availability')
CONT = D.get('cont', {})
def rows(kind):
    out = []
    if kind == 'city':
        for c in D['cities']:
            s = c[4].ljust(17, '0'); src = set(c[6].split(',')); P = 'city:' + c[0]
            out.append({f: CONT.get(P, {}).get(f, float(s[i])) for f, i in IDX.items() if f in src and s[i] != '0'})
    else:
        for k, v in D['countries'].items():
            s = v[1].ljust(17, '0'); src = set(v[3].split(',')); P = 'c:' + str(int(k))
            out.append({f: CONT.get(P, {}).get(f, float(s[i])) for f, i in IDX.items() if f in src and s[i] != '0'})
    return out
F = list(IDX)
md = ["# Do any factors overlap?", "", "Generated by `tests/overlap.py` from the built data. Published values only. A pair above 0.7 is flagged:",
      "it may be counting the same thing twice.", ""]
for kind in ('city', 'country'):
    R = rows(kind); X = np.array([[r.get(f, np.nan) for f in F] for r in R])
    keep = [j for j in range(len(F)) if np.sum(~np.isnan(X[:, j])) >= 20 and np.nanstd(X[:, j]) > 0]
    pairs = []
    for a in keep:
        for b in keep:
            if b <= a: continue
            m = ~np.isnan(X[:, a]) & ~np.isnan(X[:, b])
            if m.sum() < 20 or np.std(X[m, a]) == 0 or np.std(X[m, b]) == 0: continue
            r = float(np.corrcoef(X[m, a], X[m, b])[0, 1]); pairs.append((abs(r), r, F[a], F[b], int(m.sum())))
    pairs.sort(reverse=True)
    Z = X[:, keep].copy()
    for j in range(Z.shape[1]):
        col = Z[:, j]; mu, sd = np.nanmean(col), np.nanstd(col); col[np.isnan(col)] = mu; Z[:, j] = (col - mu) / (sd or 1)
    ev, vec = np.linalg.eigh(np.cov(Z.T)); order = np.argsort(ev)[::-1]; ev, vec = ev[order], vec[:, order]
    share = ev / ev.sum()
    md += [f"## {'Cities' if kind == 'city' else 'Countries'} ({len(R)})", "", "Flagged pairs (|r| > 0.7):", ""]
    flagged = [p for p in pairs if p[0] > 0.7]
    md += [f"- **{NAMES[a]} and {NAMES[b]}**: r = {r:+.2f} (n = {n})" for _, r, a, b, n in flagged] or ["- none"]
    md += ["", "Strongest ten pairs:", "", "| Pair | r | n |", "|---|---|---|"] + [f"| {NAMES[a]} / {NAMES[b]} | {r:+.2f} | {n} |" for _, r, a, b, n in pairs[:10]]
    md += ["", "Principal components (share of all variation; the biggest loadings):", ""]
    for i in range(3):
        load = sorted(zip(vec[:, i], [F[j] for j in keep]), key=lambda t: -abs(t[0]))[:4]
        md.append(f"- Component {i+1}: {share[i]*100:.0f}% — " + ', '.join(f"{NAMES[f]} {l:+.2f}" for l, f in load))
    md.append("")
    print(kind, 'flagged:', [(a, b, round(r, 2)) for _, r, a, b, n in flagged], '| PC1-3 share:', [round(x, 2) for x in share[:3]])
md += ["## What was changed because of this", "",
       "- Housing, cost and purchasing power were merged into **money left after rent** (salary minus a one-bedroom rent, in New York prices);",
       "  housing now measures only availability. Before the change, the old rent-burden part of housing and purchasing power both carried rent and pay.",
       "- Metro GDP now counts once in the job market instead of twice, because metro size also drives *things happening*.",
       "- Cost of living is not a scored factor (it is only used for people who work remotely for an employer elsewhere)."]
(ROOT / 'docs' / 'OVERLAP.md').write_text('\n'.join(md) + '\n', encoding='utf8')
print('wrote docs/OVERLAP.md')
